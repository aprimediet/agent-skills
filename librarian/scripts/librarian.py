#!/usr/bin/env python3
"""Librarian — Artifact management for agent knowledge.

Manages markdown files with YAML frontmatter in structured directories.
Maintains an index.md file tracking all knowledge artifacts.
Researches are organized as YYYY_MM_DD__topic directories.

All commands output JSON for easy parsing by agents.

Usage:
    python librarian.py init [--scope project|global] [--categories cat1,cat2,...]
    python librarian.py write <category> <slug> [--title TITLE] [--content CONTENT] [--file FILE] [--tags t1,t2] [--scope project|global]
    python librarian.py read <category> <slug> [--scope project|global]
    python librarian.py list [--category CATEGORY] [--scope project|global] [--tags t1,t2]
    python librarian.py search <query> [--category CATEGORY] [--scope project|global] [--field title|content|tags|all]
    python librarian.py fetch <partial> [--scope project|global]
    python librarian.py move <category> <slug> <new-category> [--scope project|global]
    python librarian.py delete <category> <slug> [--scope project|global]
    python librarian.py index [--scope project|global] [--rebuild]

Scope:
    project  — ./docs/  (relative to current working directory)
    global   — $AGENT_ROOT/docs/ or ~/.agents/docs/
"""

import argparse
import json
import os
import re
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, List, Optional, Tuple

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

DEFAULT_CATEGORIES = ["researches", "specs", "tasks", "docs"]

FRONTMATTER_TEMPLATE = """\
---
title: {title}
category: {category}
slug: {slug}
created: {created}
updated: {updated}
tags: {tags}
scope: {scope}
---

"""

INDEX_HEADER = """\
# Knowledge Index

> Auto-generated by librarian. Do not edit manually — use `python scripts/librarian.py index --rebuild` to regenerate.

"""

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def _slugify(text: str) -> str:
    """Convert text to a URL-friendly slug: lowercase, hyphens, max 60 chars."""
    text = text.lower().strip()
    text = re.sub(r"[^\w\s-]", "", text)
    text = re.sub(r"[\s_]+", "-", text)
    text = re.sub(r"-+", "-", text)
    text = text.strip("-")
    return text[:60]


def _get_base_dir(scope: str) -> Path:
    """Return the base docs directory for the given scope."""
    if scope == "global":
        agent_root = os.environ.get("AGENT_ROOT", os.path.expanduser("~/.agents"))
        return Path(agent_root) / "docs"
    return Path.cwd() / "docs"


def _parse_frontmatter(content: str) -> Tuple[Dict[str, str], str]:
    """Parse YAML frontmatter from markdown content.

    Returns (metadata_dict, body_content).
    Handles simple key: value pairs. Lists are stored as raw strings.
    """
    if not content.startswith("---"):
        return {}, content

    end = content.find("---", 3)
    if end == -1:
        return {}, content

    fm_text = content[3:end].strip()
    body = content[end + 3:].strip()

    meta: Dict[str, str] = {}
    for line in fm_text.splitlines():
        line = line.strip()
        if ":" in line:
            key, _, value = line.partition(":")
            meta[key.strip()] = value.strip()

    return meta, body


def _build_frontmatter(
    title: str,
    category: str,
    slug: str,
    created: str,
    updated: str,
    tags: List[str],
    scope: str,
) -> str:
    """Build frontmatter string."""
    tags_str = "[" + ", ".join(f'"{t}"' for t in tags) + "]"
    return FRONTMATTER_TEMPLATE.format(
        title=title,
        category=category,
        slug=slug,
        created=created,
        updated=updated,
        tags=tags_str,
        scope=scope,
    )


def _now_iso() -> str:
    """Return current UTC time as ISO 8601 string."""
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _today_prefix() -> str:
    """Return today's date as YYYY_MM_DD prefix for researches directories."""
    return datetime.now(timezone.utc).strftime("%Y_%m_%d")


def _output(data: dict) -> None:
    """Print JSON to stdout."""
    print(json.dumps(data, indent=2, ensure_ascii=False))


def _error(msg: str) -> None:
    """Print error JSON to stdout and exit."""
    _output({"error": msg})
    sys.exit(1)


def _artifact_path(base: Path, category: str, slug: str, artifact_type: Optional[str] = None) -> Path:
    """Return the file path for an artifact.

    For 'researches' category, uses date-prefixed directory structure:
        researches/YYYY_MM_DD__slug/index.md
    For 'specs' category with artifact_type, uses date-prefixed directory:
        specs/YYYY_MM_DD__slug/solution.md (for solution-architect)
        specs/YYYY_MM_DD__slug/technical.md (for technical-architect)
    For all other categories, uses flat structure:
        category/slug.md
    """
    if category == "researches":
        # Find existing date-prefixed directory for this slug
        researches_dir = base / "researches"
        if researches_dir.is_dir():
            for entry in sorted(researches_dir.iterdir()):
                if entry.is_dir() and entry.name.endswith(f"__{slug}"):
                    return entry / "index.md"
        # New artifact: create date-prefixed directory
        date_prefix = _today_prefix()
        return base / "researches" / f"{date_prefix}__{slug}" / "index.md"
    
    if category == "specs" and artifact_type:
        # Find existing date-prefixed directory for this slug
        specs_dir = base / "specs"
        if specs_dir.is_dir():
            for entry in sorted(specs_dir.iterdir()):
                if entry.is_dir() and entry.name.endswith(f"__{slug}"):
                    return entry / f"{artifact_type}.md"
        # New artifact: create date-prefixed directory
        date_prefix = _today_prefix()
        return base / "specs" / f"{date_prefix}__{slug}" / f"{artifact_type}.md"
    
    return base / category / f"{slug}.md"


def _find_slug_in_category(base: Path, category: str, slug: str, artifact_type: Optional[str] = None) -> Optional[Path]:
    """Find an artifact by slug in a category with date-prefixed directories."""
    cat_dir = base / category
    if not cat_dir.is_dir():
        return None
    for entry in sorted(cat_dir.iterdir()):
        if entry.is_dir() and entry.name.endswith(f"__{slug}"):
            if artifact_type:
                artifact_file = entry / f"{artifact_type}.md"
            else:
                artifact_file = entry / "index.md"
            if artifact_file.exists():
                return artifact_file
    return None


def _read_artifact(filepath: Path) -> Optional[Tuple[Dict[str, str], str]]:
    """Read and parse an artifact file. Returns (meta, body) or None."""
    if not filepath.exists():
        return None
    content = filepath.read_text(encoding="utf-8")
    return _parse_frontmatter(content)


def _collect_artifacts(
    base: Path, category: Optional[str] = None
) -> List[Tuple[Path, Dict[str, str], str]]:
    """Walk the docs directory and collect all artifacts.

    Returns list of (filepath, meta, body).
    """
    results: List[Tuple[Path, Dict[str, str], str]] = []

    if category:
        cat_dir = base / category
        if not cat_dir.is_dir():
            return results
        search_dirs = [cat_dir]
    else:
        if not base.is_dir():
            return results
        search_dirs = sorted(base.iterdir())

    for cat_dir in search_dirs:
        if not cat_dir.is_dir():
            continue
        cat_name = cat_dir.name

        if cat_name == "researches":
            # Date-prefixed subdirectories
            for entry in sorted(cat_dir.iterdir()):
                if entry.is_dir():
                    index_file = entry / "index.md"
                    if index_file.exists():
                        parsed = _read_artifact(index_file)
                        if parsed:
                            meta, body = parsed
                            results.append((index_file, meta, body))
        elif cat_name == "specs":
            # Mixed: date-prefixed subdirectories and flat .md files
            for entry in sorted(cat_dir.iterdir()):
                if entry.is_dir():
                    # Date-prefixed directory with solution.md or technical.md
                    for md_file in sorted(entry.glob("*.md")):
                        parsed = _read_artifact(md_file)
                        if parsed:
                            meta, body = parsed
                            results.append((md_file, meta, body))
                elif entry.suffix == ".md":
                    # Flat .md files
                    parsed = _read_artifact(entry)
                    if parsed:
                        meta, body = parsed
                        results.append((entry, meta, body))
        else:
            # Flat .md files
            for md_file in sorted(cat_dir.glob("*.md")):
                parsed = _read_artifact(md_file)
                if parsed:
                    meta, body = parsed
                    results.append((md_file, meta, body))

    return results


def _rebuild_index(base: Path) -> None:
    """Rebuild the index.md file from all artifacts."""
    artifacts = _collect_artifacts(base)

    # Group by category
    by_category: Dict[str, List[Tuple[Path, Dict[str, str], str]]] = {}
    for filepath, meta, body in artifacts:
        cat = meta.get("category", filepath.parent.parent.name if filepath.name == "index.md" else filepath.parent.name)
        if cat not in by_category:
            by_category[cat] = []
        by_category[cat].append((filepath, meta, body))

    # Build index content
    lines = [INDEX_HEADER]

    for cat in sorted(by_category.keys()):
        cat_artifacts = by_category[cat]
        # Category heading
        lines.append(f"## {cat.title()}\n")

        for filepath, meta, body in sorted(cat_artifacts, key=lambda x: x[1].get("updated", x[1].get("created", "")), reverse=True):
            title = meta.get("title", filepath.stem)
            slug = meta.get("slug", filepath.stem)
            tags_raw = meta.get("tags", "[]")
            try:
                tags = json.loads(tags_raw)
            except (json.JSONDecodeError, TypeError):
                tags = []
            created = meta.get("created", "")
            updated = meta.get("updated", "")

            # Relative path from docs root
            rel_path = filepath.relative_to(base)
            tag_str = " ".join(f"`{t}`" for t in tags) if tags else ""
            date_str = updated[:10] if updated else (created[:10] if created else "")

            lines.append(f"- [{title}]({rel_path}) — {date_str} {tag_str}")

        lines.append("")

    index_path = base / "index.md"
    index_path.write_text("\n".join(lines), encoding="utf-8")


