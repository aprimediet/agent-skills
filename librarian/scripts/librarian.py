def main() -> None:
    parser = argparse.ArgumentParser(
        description="Librarian — Artifact management for agent knowledge",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    subparsers = parser.add_subparsers(dest="command", help="Command to run")

    # Common arguments
    def _add_scope(p: argparse.ArgumentParser) -> None:
        p.add_argument("--scope", choices=["project", "global"], default="project",
                       help="Scope: project (./docs/) or global ($AGENT_ROOT/docs/)")

    # init
    p_init = subparsers.add_parser("init", help="Initialize directory structure")
    _add_scope(p_init)
    p_init.add_argument("--categories", default=None,
                        help="Comma-separated categories (default: researches,specs,tasks,docs)")

    # write
    p_write = subparsers.add_parser("write", help="Write or update an artifact")
    p_write.add_argument("category", help="Category (e.g., researches, specs, tasks)")
    p_write.add_argument("slug", help="Slug for the artifact (auto-slugified)")
    p_write.add_argument("--title", help="Title (defaults to slugified title)")
    p_write.add_argument("--content", help="Content string")
    p_write.add_argument("--file", help="Read content from file")
    p_write.add_argument("--tags", help="Comma-separated tags")
    p_write.add_argument("--artifact-type", dest="artifact_type", default=None,
                         help="Artifact type for specs category (solution, technical)")
    _add_scope(p_write)

    # read
    p_read = subparsers.add_parser("read", help="Read an artifact")
    p_read.add_argument("category", help="Category")
    p_read.add_argument("slug", help="Artifact slug")
    p_read.add_argument("--artifact-type", dest="artifact_type", default=None,
                         help="Artifact type for specs category (solution, technical)")
    _add_scope(p_read)

    # list
    p_list = subparsers.add_parser("list", help="List artifacts")
    p_list.add_argument("--category", default=None, help="Filter by category")
    p_list.add_argument("--tags", default=None, help="Filter by tags (comma-separated)")
    _add_scope(p_list)

    # search
    p_search = subparsers.add_parser("search", help="Full-text search")
    p_search.add_argument("query", help="Search query")
    p_search.add_argument("--category", default=None, help="Filter by category")
    p_search.add_argument("--field", choices=["title", "content", "tags", "all"], default="all",
                          help="Search in specific field")
    _add_scope(p_search)

    # fetch
    p_fetch = subparsers.add_parser("fetch", help="Find artifact by partial slug or title")
    p_fetch.add_argument("partial", help="Partial slug or title to match")
