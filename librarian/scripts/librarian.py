def cmd_init(args: argparse.Namespace) -> None:
    """Initialize the directory structure."""
    base = _get_base_dir(args.scope)
    categories = args.categories.split(",") if args.categories else DEFAULT_CATEGORIES
    created = []

    for cat in categories:
        cat = cat.strip()
        cat_dir = base / cat
        cat_dir.mkdir(parents=True, exist_ok=True)
        created.append(str(cat_dir))

    # Create initial index
    _rebuild_index(base)

    _output({
        "action": "init",
        "scope": args.scope,
        "base": str(base),
        "directories": created,
        "index": str(base / "index.md"),
    })


def cmd_write(args: argparse.Namespace) -> None:
    """Write or update an artifact."""
    base = _get_base_dir(args.scope)
    slug = _slugify(args.slug) if args.slug else _slugify(args.title or "untitled")
    category = args.category
    title = args.title or slug.replace("-", " ").title()

    # Ensure category directory exists
    cat_dir = base / category
    cat_dir.mkdir(parents=True, exist_ok=True)

    artifact_type = getattr(args, 'artifact_type', None)
    filepath = _artifact_path(base, category, slug, artifact_type)

    # Get content
    if args.file:
        content = Path(args.file).read_text(encoding="utf-8")
    elif args.content:
        content = args.content
    elif not sys.stdin.isatty():
        content = sys.stdin.read()
    else:
        content = ""

    # Handle existing artifact (preserve created date)
    now = _now_iso()
    existing = _read_artifact(filepath)
    if existing:
        created = existing[0].get("created", now)
        # If no new content provided and file exists, just update metadata
        if not args.content and not args.file and sys.stdin.isatty():
            # Preserve existing body
            content = existing[1]
    else:
        created = now

    # Merge tags
    tags = args.tags.split(",") if args.tags else []
    if existing and not args.tags:
        # Preserve existing tags if none specified
        existing_tags = existing[0].get("tags", "[]")
        try:
            tags = json.loads(existing_tags)
        except (json.JSONDecodeError, TypeError):
            tags = []

    frontmatter = _build_frontmatter(
        title=title, category=category, slug=slug,
        created=created, updated=now, tags=tags, scope=args.scope,
    )

    full_content = frontmatter + content

    # Ensure parent directory exists (for researches date-prefixed dirs)
    filepath.parent.mkdir(parents=True, exist_ok=True)
    filepath.write_text(full_content, encoding="utf-8")

    # Rebuild index
    _rebuild_index(base)

    _output({
        "action": "write",
        "path": str(filepath),
        "slug": slug,
        "category": category,
        "title": title,
        "scope": args.scope,
        "created": created,
        "updated": now,
        "tags": tags,
    })


def cmd_read(args: argparse.Namespace) -> None:
    """Read an artifact."""
    base = _get_base_dir(args.scope)
    slug = args.slug
    category = args.category

    artifact_type = getattr(args, 'artifact_type', None)
    filepath = _artifact_path(base, category, slug, artifact_type)
    parsed = _read_artifact(filepath)

    if not parsed:
        _error(f"Artifact not found: {category}/{slug}")

    meta, body = parsed
    _output({
        "action": "read",
        "path": str(filepath),
        "slug": slug,
        "category": category,
        "scope": args.scope,
        "meta": meta,
        "body": body,
    })


def cmd_list(args: argparse.Namespace) -> None:
    """List artifacts, optionally filtered by category and tags."""
    base = _get_base_dir(args.scope)
    artifacts = _collect_artifacts(base, category=args.category)

    # Filter by tags if specified
    filter_tags = args.tags.split(",") if args.tags else None
    results = []

    for filepath, meta, body in artifacts:
        if filter_tags:
            try:
                artifact_tags = json.loads(meta.get("tags", "[]"))
            except (json.JSONDecodeError, TypeError):
                artifact_tags = []
            if not any(t in artifact_tags for t in filter_tags):
                continue

        results.append({
            "slug": meta.get("slug", filepath.stem),
            "title": meta.get("title", filepath.stem),
            "category": meta.get("category", filepath.parent.name),
            "created": meta.get("created", ""),
            "updated": meta.get("updated", ""),
            "tags": meta.get("tags", "[]"),
            "path": str(filepath),
        })

    _output({
        "action": "list",
        "scope": args.scope,
        "category": args.category or "all",
        "count": len(results),
        "artifacts": results,
    })


def cmd_search(args: argparse.Namespace) -> None:
    """Full-text search across artifacts."""
    base = _get_base_dir(args.scope)
    query = args.query.lower()
    field = args.field or "all"
    artifacts = _collect_artifacts(base, category=args.category)

    results = []
    for filepath, meta, body in artifacts:
        score = 0.0
        matches = []

        # Search in title
        if field in ("all", "title"):
            title = meta.get("title", "").lower()
            if query in title:
                score += 2.0
                matches.append("title")

        # Search in tags
        if field in ("all", "tags"):
            try:
                tags = json.loads(meta.get("tags", "[]"))
            except (json.JSONDecodeError, TypeError):
                tags = []
            if any(query in t.lower() for t in tags):
                score += 1.5
                matches.append("tags")

        # Search in content
        if field in ("all", "content"):
            if query in body.lower():
                # Count occurrences for relevance
                count = body.lower().count(query)
                score += min(count * 0.1, 1.0)
                matches.append("content")

        # Search in category/slug
        if field == "all":
            if query in meta.get("category", "").lower():
                score += 0.5
                matches.append("category")
            if query in meta.get("slug", "").lower():
                score += 0.5
                matches.append("slug")

        if score > 0:
            results.append({
                "slug": meta.get("slug", filepath.stem),
                "title": meta.get("title", filepath.stem),
                "category": meta.get("category", filepath.parent.name),
                "score": round(score, 2),
                "matched_in": matches,
                "path": str(filepath),
            })

    # Sort by score descending
    results.sort(key=lambda r: r["score"], reverse=True)

    _output({
        "action": "search",
        "query": args.query,
        "scope": args.scope,
        "category": args.category or "all",
        "field": field,
        "count": len(results),
        "results": results,
    })


def cmd_fetch(args: argparse.Namespace) -> None:
    """Find an artifact by partial slug or title match."""
    base = _get_base_dir(args.scope)
    partial = args.partial.lower()
    artifacts = _collect_artifacts(base)

    # Score matches
    candidates = []
    for filepath, meta, body in artifacts:
        slug = meta.get("slug", filepath.stem).lower()
        title = meta.get("title", "").lower()
        score = 0.0

        if slug == partial:
            score = 3.0  # Exact slug match
        elif slug.startswith(partial):
            score = 2.0  # Slug prefix match
        elif partial in slug:
            score = 1.5  # Slug contains
        elif title == partial:
            score = 2.5  # Exact title match
        elif partial in title:
            score = 1.0  # Title contains

        if score > 0:
            candidates.append({
                "slug": meta.get("slug", filepath.stem),
                "title": meta.get("title", filepath.stem),
                "category": meta.get("category", filepath.parent.name),
                "score": score,
                "path": str(filepath),
            })

    candidates.sort(key=lambda c: c["score"], reverse=True)

    _output({
        "action": "fetch",
        "partial": args.partial,
        "scope": args.scope,
        "count": len(candidates),
        "results": candidates[:10],  # Limit to top 10
    })


def cmd_move(args: argparse.Namespace) -> None:
    """Move an artifact to a different category."""
    base = _get_base_dir(args.scope)
    slug = args.slug
    old_category = args.category
    new_category = args.new_category
    artifact_type = getattr(args, 'artifact_type', None)

    old_path = _artifact_path(base, old_category, slug, artifact_type)
    parsed = _read_artifact(old_path)
    if not parsed:
        _error(f"Artifact not found: {old_category}/{slug}")

    meta, body = parsed

    # Ensure new category directory exists
    new_cat_dir = base / new_category
    new_cat_dir.mkdir(parents=True, exist_ok=True)

    new_path = _artifact_path(base, new_category, slug, artifact_type)

    # Update frontmatter
    now = _now_iso()
    try:
        tags = json.loads(meta.get("tags", "[]"))
    except (json.JSONDecodeError, TypeError):
        tags = []

    frontmatter = _build_frontmatter(
        title=meta.get("title", slug.replace("-", " ").title()),
        category=new_category,
        slug=slug,
        created=meta.get("created", now),
        updated=now,
        tags=tags,
        scope=args.scope,
    )

    # Ensure parent directory exists (for researches date-prefixed dirs)
    new_path.parent.mkdir(parents=True, exist_ok=True)
    new_path.write_text(frontmatter + body, encoding="utf-8")

    # Remove old file and empty parent dir if it was a researches date-dir
    old_path.unlink()
    if old_category == "researches" and old_path.parent != base / "researches":
        # Try to remove the date-prefixed directory if empty
        try:
            old_path.parent.rmdir()
        except OSError:
            pass  # Directory not empty, leave it

    # Rebuild index
    _rebuild_index(base)

    _output({
        "action": "move",
        "slug": slug,
        "from": old_category,
        "to": new_category,
        "old_path": str(old_path),
        "new_path": str(new_path),
        "scope": args.scope,
    })


def cmd_delete(args: argparse.Namespace) -> None:
    """Delete an artifact."""
    base = _get_base_dir(args.scope)
    slug = args.slug
    category = args.category
    artifact_type = getattr(args, 'artifact_type', None)

    filepath = _artifact_path(base, category, slug, artifact_type)
    if not filepath.exists():
        _error(f"Artifact not found: {category}/{slug}")

    filepath.unlink()

    # Clean up empty date-prefixed directory for researches
    if category == "researches" and filepath.parent != base / "researches":
        try:
            filepath.parent.rmdir()
        except OSError:
            pass  # Directory not empty, leave it
    
    # Clean up empty date-prefixed directory for specs
    if category == "specs" and artifact_type and filepath.parent != base / "specs":
        try:
            filepath.parent.rmdir()
        except OSError:
            pass  # Directory not empty, leave it

    # Rebuild index
    _rebuild_index(base)

    _output({
        "action": "delete",
        "slug": slug,
        "category": category,
        "path": str(filepath),
        "scope": args.scope,
    })


def cmd_index(args: argparse.Namespace) -> None:
    """Rebuild and display the knowledge index."""
    base = _get_base_dir(args.scope)

    if args.rebuild:
        _rebuild_index(base)

    index_path = base / "index.md"
    if not index_path.exists():
        _error("Index not found. Run with --rebuild to create it.")

    content = index_path.read_text(encoding="utf-8")
    _output({
        "action": "index",
        "scope": args.scope,
        "path": str(index_path),
        "content": content,
    })


